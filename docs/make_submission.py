"""Write SUBMISSION.md (fields for hackathon.lexsi.ai/submission) with the abstract copied verbatim from ABSTRACT.md
and its word count computed, then check that every link in it answers 200 without credentials.

    python docs/make_submission.py [--no-check]
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
GITHUB = "https://github.com/bennytimz/aftermarket"
SPACE = "https://huggingface.co/spaces/bennytimz/aftermarket"
MODELS_COLL = "https://huggingface.co/collections/bennytimz/aftermarket-am-defense-controls-6af9984fc9b6f21539d82a59"
DATA_COLL = "https://huggingface.co/collections/bennytimz/aftermarket-evaluation-data-6af998b5c1860f5bc2df2b27"
TEAM_RUNS = ["SDT", "GC", "IL", "RL", "ST", "SP"]
TEAMS = {"SDT": "Safety Doesn't Translate: one-shot weight repair (published 1% setting)",
         "GC": "Guardián colombiano: Lisa hardening (LoRA)", "IL": "Intentlock: SafeGrad hardening (LoRA)",
         "RL": "RedLens guard: prompt guard in the chat template", "ST": "ScarTissue: rank-one sparse repair (2% patch)",
         "SP": "SafetyPulse: SafeTune safety-vector repair"}


def abstract() -> tuple[str, int]:
    body = (ROOT / "ABSTRACT.md").read_text(encoding="utf-8").split("\n", 1)[1].strip()
    words = [w for w in re.findall(r"\S+", re.sub(r"[#*`]", " ", body)) if re.search(r"[A-Za-z0-9]", w)]
    return body, len(words)


def build() -> str:
    reg = yaml.safe_load((ROOT / "configs" / "models.yaml").read_text(encoding="utf-8"))
    text, n = abstract()
    models = [f"- `{reg['base_model']}` @ `{reg['base_revision']}` (base model): "
              f"https://huggingface.co/{reg['base_model']}/tree/{reg['base_revision']}"]
    for k in TEAM_RUNS:
        m = reg["models"][k]
        models.append(f"- `{m['hf_path']}` @ `{m['revision'][:12]}` ({k}, {TEAMS[k]}): https://huggingface.co/{m['hf_path']}")
    plain = re.sub(r"\*\*|`", "", text)
    plain = "\n\n".join(" ".join(par.split()) for par in plain.split("\n\n"))  # one line per paragraph: pastes cleanly
    return f"""# Submission: hackathon.lexsi.ai/submission

Every field below is ready to paste. Generated by `python docs/make_submission.py` (links checked: 200, no login).

## Registered email

<YOUR REGISTERED EMAIL>

## Project title

Aftermarket: does a safety fix survive the next person who downloads the model?

## Track

Track 2 (AI Red Teaming, Safety and Alignment)

## Problem statements

- 2a #1 (primary): red-teaming and robustness, including weight-space attacks
- 2b #12: tamper resistance
- 2b #11: safety under compression
- 2b #9: locating safety

## Lexsi repos used

- CuratorKIT: built every evaluation split and fine-tuning set (cleaning, exact and MinHash dedup against the splits, pinned sources, provenance manifests).
- SafeTune: best-of-N augmentations for the A5bon attack, safety-neuron scores for locating layers, and SafeGrad hardening for our defense AM.
- AuditKIT: paired-bootstrap significance tests behind every model-vs-base comparison (Holm-adjusted).
- CircuitKIT: discovery was attempted but did not run on Tiny Aya (EAP-IG ran out of memory on a T4 and on CPU), so it is not used in any result.

One line: built on CuratorKIT, SafeTune and AuditKIT; CircuitKIT discovery was attempted but did not run on Tiny Aya.

## Models

{chr(10).join(models)}
- Ours (public, with model cards): AM and its controls AM_rand0, AM_rand1, AM_all: {MODELS_COLL}

## Abstract ({n} words)

{plain}

## Links

- GitHub repository: {GITHUB}
- Hugging Face Space (leaderboard, report cards): {SPACE}
- Hugging Face model collection (AM + controls): {MODELS_COLL}
- Hugging Face dataset collection (eval splits, metric and verdict tables, hand labels, run manifests, CuratorKIT manifests): {DATA_COLL}
- Write-up: {GITHUB}/blob/main/README.md
"""


def links(md: str) -> list[str]:
    return sorted(set(re.findall(r"https://[^\s)>]+", md)))


def check(md: str) -> list[tuple[int, str]]:
    import requests

    bad = []
    for u in links(md):
        code = requests.get(u, timeout=30, allow_redirects=True, headers={"User-Agent": "aftermarket-linkcheck"}).status_code
        print(code, u)
        if code != 200:
            bad.append((code, u))
    return bad


def main() -> None:
    md = build()
    (ROOT / "SUBMISSION.md").write_text(md, encoding="utf-8")
    print(f"SUBMISSION.md written; abstract {abstract()[1]} words")
    if "--no-check" not in sys.argv and check(md):
        raise SystemExit("some links did not return 200")


if __name__ == "__main__":
    main()
